#!/usr/bin/env python3
"""Turn a .NET extension applicationHost.xdt (RemoveAll + Insert lines) into the one-operation
custom-transform file that does the same thing through Datadog.AzureAppServices.DotNet.Xdt.dll.

    make-custom-xdt.py <applicationHost.xdt> <output.xdt> [--import-path PATH]

Works on the repository's template (placeholders like vFOLDERUNKNOWN stay as they are, so
install.ps1 still fills them in) and on an installed file. Refuses anything it doesn't understand,
so a change to the source file can't be silently dropped.
"""
import argparse
import sys
import xml.etree.ElementTree as ET

XDT = "http://schemas.microsoft.com/XML-Document-Transform"
T, L = f"{{{XDT}}}Transform", f"{{{XDT}}}Locator"
DEFAULT_IMPORT = r"%XDT_EXTENSIONPATH%\vFOLDERUNKNOWN\Datadog.AzureAppServices.DotNet.Xdt.dll"


def fail(message):
    sys.exit(f"make-custom-xdt: {message}")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("source")
    parser.add_argument("output")
    parser.add_argument("--import-path", default=DEFAULT_IMPORT)
    args = parser.parse_args()

    root = ET.parse(args.source).getroot()
    if root.tag != "configuration" or [c.tag for c in root] != ["system.webServer"]:
        fail("expected <configuration> with only <system.webServer>")
    web = root[0]
    if [c.tag for c in web] != ["runtime"] or [c.tag for c in web[0]] != ["environmentVariables"]:
        fail("expected only system.webServer/runtime/environmentVariables")
    if web[0].get(T) != "InsertIfMissing" or web[0][0].get(T) != "InsertIfMissing":
        fail("runtime and environmentVariables must be InsertIfMissing")

    removed, inserts, if_missing = [], [], []
    for add in web[0][0]:
        if add.tag != "add" or add.get(L) != "Match(name)":
            fail(f"unexpected element {add.tag} {add.attrib}")
        name, transform = add.get("name"), add.get(T)
        extra = set(add.attrib) - {"name", "value", T, L}
        if not name or extra:
            fail(f"unexpected attributes on {name}: {extra}")
        if transform == "RemoveAll":
            removed.append(name)
        elif transform == "Insert":
            inserts.append((name, add.get("value")))
        elif transform == "InsertIfMissing":
            if_missing.append((name, add.get("value")))
        else:
            fail(f"unexpected transform {transform} on {name}")

    inserted = {n for n, _ in inserts}
    for name, _ in inserts:
        if name not in removed:
            # Today's Insert without a RemoveAll would add a duplicate; refuse rather than guess.
            fail(f"{name} is inserted without being removed first")
    for name, _ in if_missing:
        if name in removed or name in inserted:
            fail(f"{name} is both InsertIfMissing and removed or inserted")

    def esc(value):
        return (value.replace("&", "&amp;").replace('"', "&quot;").replace("<", "&lt;").replace(">", "&gt;"))

    lines = [
        '<?xml version="1.0"?>',
        "<!-- Generated by make-custom-xdt.py from the RemoveAll + Insert file. Do not edit by hand. -->",
        f'<configuration xmlns:xdt="{XDT}">',
        f'  <xdt:Import path="{esc(args.import_path)}" namespace="Datadog.AzureAppServices.DotNet.Xdt" />',
        '  <system.webServer xdt:Transform="SetEnvironmentVariables">',
    ]
    lines += [f'    <remove name="{esc(n)}" />' for n in removed if n not in inserted]
    lines += [f'    <add name="{esc(n)}" value="{esc(v)}" />' for n, v in inserts]
    lines += [f'    <addIfMissing name="{esc(n)}" value="{esc(v)}" />' for n, v in if_missing]
    lines += ["  </system.webServer>", "</configuration>", ""]
    open(args.output, "w", encoding="utf-8", newline="\r\n").write("\n".join(lines))
    print(f"{args.output}: {len(inserts)} set, {len(if_missing)} set if missing, "
          f"{len([n for n in removed if n not in inserted])} removed")


main()
